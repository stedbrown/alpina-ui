import { execFileSync } from 'node:child_process'
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import ts from 'typescript'

const report = 'etc/alpina-ui.api.md'
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed, removeComments: true })

// Capture declaration dependencies as well as entry points. For example, a change
// to the private Slot type changes the public Button signature without editing Button.
export async function declarationReport(dist) {
  const entry = path.resolve(dist, 'index.d.ts')
  const program = ts.createProgram([entry], {
    module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext,
    types: [], noLib: true, skipLibCheck: true,
  })
  const sections = []
  for (const source of program.getSourceFiles()) {
    const name = path.relative(dist, source.fileName).split(path.sep).join('/')
    if (name.startsWith('../') || path.isAbsolute(name)) continue
    const tags = []
    const collect = (node, parent) => {
      const key = node.name ? [parent, node.name.getText(source)].filter(Boolean).join('.') : parent
      for (const tag of ts.getJSDocTags(node).filter(tag => tag.tagName.text === 'deprecated')) {
        tags.push('@deprecated ' + key + ' ' + (ts.getTextOfJSDocComment(tag.comment) ?? ''))
      }
      ts.forEachChild(node, child => collect(child, key))
    }
    const documented = ts.createSourceFile(name, source.text, ts.ScriptTarget.Latest, true)
    collect(documented, '')
    const runtime = await readFile(path.join(dist, name.replace(/\.d\.ts$/, '.js')), 'utf8')
    const client = /^['"]use client['"];?/m.test(runtime.trimStart().split('\n', 1)[0])
    sections.push([name, ['## ' + name, client ? 'Client entry.' : '', ...tags,
      '~~~ts', printer.printFile(source).trim(), '~~~'].filter(Boolean).join('\n')])
  }
  if (!sections.some(([name]) => name === 'index.d.ts')) throw Error('Run npm run build before checking the API.')
  return sections.sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([, section]) => section).join('\n\n')
}

export async function publicReport(root) {
  const read = name => readFile(path.join(root, name), 'utf8')
  const { exports: entries, bin, engines, peerDependencies } = JSON.parse(await read('package.json'))
  const { items } = JSON.parse(await read('registry.json'))
  const blocks = (await readdir(path.join(root, 'blocks'))).filter(name => /^[a-z0-9-]+\.tsx$/.test(name))
  const tokens = [...new Set([...((await read('src/theme.css')).matchAll(/^\s*(--al-[\w-]+):/gm))].map(match => match[1]))].sort()
  const cli = execFileSync(process.execPath, ['cli/alpina.mjs', '--help'], { cwd: root, encoding: 'utf8' }).trim().replaceAll('\r\n', '\n')
  return ['# Alpina UI public API', 'Generated by npm run api:update. Review changes alongside the changelog.',
    '## Package entry points', '~~~json\n' + JSON.stringify({ exports: entries, bin, engines, peerDependencies }, null, 2) + '\n~~~',
    '## CLI', '~~~text\n' + cli + '\n~~~', '## Registry and stylesheet names',
    items.map(item => '- ' + item.group + '/' + item.name + ' · styles/' + item.name + '.css').sort().join('\n'),
    '## Copyable blocks', blocks.sort().map(name => '- block/' + name.slice(0, -4)).join('\n'),
    '## Theme properties', tokens.map(name => '- ' + name).join('\n'),
    await declarationReport(path.join(root, 'dist'))].join('\n\n') + '\n'
}

export function requireApiNote(diff) {
  if (!/^\+- \*\*Public API\*\* \S.+/m.test(diff)) {
    throw Error('Describe the API change and any migration in a new CHANGELOG.md bullet beginning with "- **Public API** ".')
  }
}

async function main() {
  const root = fileURLToPath(new URL('../', import.meta.url))
  const actual = await publicReport(root)
  const target = path.join(root, report)
  if (process.argv.includes('--update')) {
    await mkdir(path.dirname(target), { recursive: true })
    await writeFile(target, actual)
    return
  }
  const expected = (await readFile(target, 'utf8')).replaceAll('\r\n', '\n')
  if (expected !== actual) throw Error('Public API differs from the reviewed report. Run npm run api:update and review git diff.')
  const base = process.env.ALPINA_API_BASE
  if (base && !/^0+$/.test(base)) {
    if (!/^[a-f0-9]{40,64}$/.test(base)) throw Error('Expected a Git commit ID in ALPINA_API_BASE.')
    const diff = file => execFileSync('git', ['diff', '--no-ext-diff', '--unified=0', base, 'HEAD', '--', file],
      { cwd: root, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 })
    if (diff(report)) requireApiNote(diff('CHANGELOG.md'))
  }
  console.log('Public API matches the reviewed report.')
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) await main()
