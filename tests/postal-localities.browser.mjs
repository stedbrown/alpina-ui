import assert from 'node:assert/strict'
import { launchBrowser } from './launch-browser.mjs'
import { openPublicPage, siteOrigin } from './public-pages.mjs'

const browser = await launchBrowser()
try {
  const page = await openPublicPage(browser, { viewport: { width: 360, height: 800 } })
  const requests = []
  const chunk = /\/postal-localities\.data-[^/]+\.js$/
  page.on('request', request => requests.push(request.url()))
  let release
  const pause = new Promise(resolve => { release = resolve })
  await page.route(chunk, async route => { await pause; await route.fallback() })
  await page.goto(siteOrigin + '/docs/components/swiss-address-form/')
  const form = page.getByRole('form')
  const postcode = form.locator('[name="postalCode"]')
  const locality = form.locator('[name="locality"]')
  const canton = form.locator('[name="canton"]')
  await postcode.fill('690')
  assert.equal(requests.filter(url => chunk.test(url)).length, 0)
  await Promise.all([page.waitForRequest(request => chunk.test(request.url())), postcode.fill('6900')])
  await postcode.fill('1085')
  await locality.fill('Draft locality')
  release()
  const options = form.getByRole('combobox', { name: /Suggerimenti per il NPA 1085/ })
  await options.waitFor()
  assert.equal(await locality.inputValue(), 'Draft locality')
  assert.deepEqual(await options.locator('option:not([disabled])').allTextContents(), ['Vulliens (FR)', 'Vulliens (VD)'])
  await options.selectOption({ label: 'Vulliens (VD)' })
  assert.equal(await locality.inputValue(), 'Vulliens')
  assert.equal(await canton.inputValue(), 'VD')
  await postcode.fill('6900')
  const lugano = form.getByRole('combobox', { name: /Suggerimenti per il NPA 6900/ })
  await lugano.selectOption({ label: 'Massagno (TI)' })
  assert.equal(await locality.inputValue(), 'Massagno')
  assert.equal(await canton.inputValue(), 'TI')
  await locality.fill('Manual override')
  assert.equal(await lugano.inputValue(), '')
  await postcode.fill('3001')
  await form.getByText('Nessun suggerimento. Inserisci la località e il cantone.').waitFor()
  assert.equal(await locality.inputValue(), 'Manual override')
  assert.equal(await canton.inputValue(), 'TI')
  assert.equal(requests.filter(url => chunk.test(url)).length, 1)
  assert.ok(!requests.some(url => url.includes('/postal-source-')))
  await page.getByRole('button', { name: 'Source', exact: true }).click()
  await page.getByLabel('Distributed files').selectOption('swiss/postal-localities.data.ts')
  await page.locator('pre').filter({ hasText: '6900TIMassagno' }).waitFor()
  assert.ok(requests.some(url => url.includes('/postal-source-')))
  const offline = await browser.newContext({ offline: true })
  const file = await offline.newPage()
  await file.goto(new URL('../site/catalog.html#swiss-address-form', import.meta.url).href)
  await file.locator('[name="postalCode"]').fill('6900')
  await file.getByRole('combobox', { name: /Suggerimenti per il NPA 6900/ }).selectOption({ label: 'Paradiso (TI)' })
  assert.equal(await file.locator('[name="locality"]').inputValue(), 'Paradiso')
  console.log('Postal lookup passed lazy loading, concurrent edits, canton disambiguation, manual entry, source view and offline use.')
} finally { await browser.close() }
